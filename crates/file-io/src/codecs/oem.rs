//! DOS/OEM code pages that encoding_rs lacks (BIZ-09). Bytes 0x00–0x7F are ASCII;
//! each table maps 0x80–0xFF to 128 distinct scalars (the Unicode Consortium's
//! vendor mappings, as Windows `MultiByteToWideChar` decodes them without
//! MB_USEGLYPHCHARS). Every byte decodes, so these pages never yield opaque
//! spans, and encoding is the exact inverse: other scalars are unrepresentable.
use super::Encoding;

/// The upper half of `encoding`, or `None` for encodings served elsewhere.
pub(super) fn table(encoding: Encoding) -> Option<&'static [char; 128]> {
    match encoding {
        Encoding::Cp437 => Some(&CP437),
        Encoding::Cp850 => Some(&CP850),
        Encoding::Cp852 => Some(&CP852),
        _ => None,
    }
}
pub(super) fn decode(table: &[char; 128], byte: u8) -> char {
    match byte.checked_sub(0x80) {
        Some(index) => table[usize::from(index)],
        None => char::from(byte),
    }
}
pub(super) fn encode(table: &[char; 128], c: char) -> Option<u8> {
    if c.is_ascii() {
        return Some(c as u8);
    }
    let index = table.iter().position(|&mapped| mapped == c)?;
    u8::try_from(0x80 + index).ok()
}

